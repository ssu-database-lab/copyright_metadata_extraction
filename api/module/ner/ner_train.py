def create_char_bio_tags(text, entities):
    """문자 단위로 정확한 BIO 태그 생성 - NER 표준 준수 (개선판)"""
    tags = ['O'] * len(text)
    
    # 엔티티를 길이 순으로 정렬 (긴 것부터 처리하여 겹침 방지)
    # 동일 길이면 출현 위치 순으로 정렬
    sorted_entities = sorted(entities, key=lambda x: (len(x[0]), -text.find(x[0])), reverse=True)
    
    used_positions = set()  # 이미 사용된 위치 추적
    
    for entity_text, entity_type in sorted_entities:
        if entity_type not in ENTITY_TYPES or not entity_text.strip():
            continue
        
        # 엔티티 텍스트 정규화 (앞뒤 공백 제거)
        entity_text_clean = entity_text.strip()
        if not entity_text_clean:
            continue
            
        # 정확한 매칭을 위해 모든 출현 위치 찾기
        start = 0
        while True:
            pos = text.find(entity_text_clean, start)
            if pos == -1:
                break
            
            end_pos = pos + len(entity_text_clean)
            
            # 해당 위치가 이미 다른 엔티티로 태깅되었는지 확인
            position_range = range(pos, end_pos)
            if any(p in used_positions for p in position_range):
                start = pos + 1
                continue
            
            # 단어 경계 확인 (선택적 - 더 정확한 매칭)
            # 앞뒤로 한글/영문/숫자가 있으면 단어 중간이므로 스킵
            if pos > 0 and text[pos - 1].isalnum():
                start = pos + 1
                continue
            if end_pos < len(text) and text[end_pos].isalnum():
                start = pos + 1
                continue
            
            # B-I-O 태깅
            first_char_tagged = False
            for i in range(pos, end_pos):
                if text[i].strip():  # 공백이 아닌 문자만
                    if not first_char_tagged:
                        tags[i] = f'B-{entity_type}'
                        first_char_tagged = True
                    else:
                        tags[i] = f'I-{entity_type}'
                    used_positions.add(i)
                # 공백은 O로 유지 (토크나이저와의 정합성)
            
            start = pos + 1
    
    return tags

